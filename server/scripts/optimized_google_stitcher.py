            point_cloud = self._generate_pointcloud(photos, depth_maps)
            if point_cloud and point_cloud.get('pointsIncluded', 0) > 0:
                print(f"[OptimizedStitcher] Point cloud: {point_cloud['totalPointsGenerated']:,} generated, {point_cloud['pointsIncluded']:,} included", file=sys.stderr)
                
                # Apply default 0.41x scaling to point cloud for accurate measurements
                # This corrects for typical depth sensor overestimation
                print(f"[OptimizedStitcher] Applying default depth scale: {depth_scale_applied}x", file=sys.stderr)
                scaled_points = (np.array(point_cloud['points']) * depth_scale_applied).tolist()
                point_cloud['points'] = scaled_points
                point_cloud['depthScaleApplied'] = depth_scale_applied
                
                # Calculate room dimensions from scaled point cloud
                room_dims_from_cloud = self._calculate_room_dimensions_from_pointcloud(point_cloud, depth_scale=1.0, auto_calibrate=False)
                if room_dims_from_cloud:
                    room_dims_from_cloud['depthScaleApplied'] = depth_scale_applied
                    print(f"[Point Cloud Dimensions] {room_dims_from_cloud['widthMeters']:.1f}m × {room_dims_from_cloud['lengthMeters']:.1f}m × {room_dims_from_cloud['heightMeters']:.1f}m", file=sys.stderr)
                    print(f"[Point Cloud Dimensions]   ({room_dims_from_cloud['widthFeet']:.1f}ft × {room_dims_from_cloud['lengthFeet']:.1f}ft × {room_dims_from_cloud['heightFeet']:.1f}ft)", file=sys.stderr)
                    print(f"[Point Cloud Dimensions]   Floor area: {room_dims_from_cloud['floorAreaSqFt']:.0f} sq ft | Volume: {room_dims_from_cloud['volumeCuFt']:.0f} cu ft", file=sys.stderr)
