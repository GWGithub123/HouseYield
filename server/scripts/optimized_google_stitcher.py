@dataclass
class ImageMatch:
    """Verified match between two images"""
    idx1: int
    idx2: int
    matches: List[cv2.DMatch]
    homography: np.ndarray
    inliers: int
    confidence: float
    overlap_area: float


@dataclass
class CameraRefinement:
    """Small angular refinement from feature matching"""
    image_idx: int
    delta_azimuth: float  # degrees, clamped to ±5°
    delta_elevation: float  # degrees, clamped to ±5°
    confidence: float


