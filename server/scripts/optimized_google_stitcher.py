class SensorAnchoredRefiner:
    """
    Refine camera poses using feature matches BUT constrained to sensor data.
    
    This is the KEY difference from unconstrained bundle adjustment:
    - Sensor data (gyro/compass) is TRUSTED
    - Feature matching only provides small corrections (max ±5°)
    - Prevents catastrophic warping from sparse matches
    """
    
    def __init__(self, max_refinement_deg: float = 5.0):
        self.max_refinement_deg = max_refinement_deg
    
    def compute_refinements(
        self,
        photos: List[Dict],
        matches: List[ImageMatch],
        images: List[np.ndarray]
    ) -> List[CameraRefinement]:
        """
        Compute small angular refinements for each camera.
        
        Returns refinements clamped to ±max_refinement_deg.
        """
        n = len(photos)
        refinements = []
        
        # Build adjacency: which images have verified matches
        adj = {i: [] for i in range(n)}
        for match in matches:
            adj[match.idx1].append(match)
            adj[match.idx2].append(match)
        
        for i in range(n):
            if not adj[i]:
                # No matches, keep sensor data exactly
                refinements.append(CameraRefinement(i, 0.0, 0.0, 0.0))
                continue
            
            # Compute weighted average correction from all neighbors
            delta_az_sum = 0.0
            delta_el_sum = 0.0
            weight_sum = 0.0
            
            for match in adj[i]:
                # Determine which image is the neighbor
                neighbor_idx = match.idx2 if match.idx1 == i else match.idx1
                
                # Estimate angular difference from homography
                # (simplified: use homography decomposition or geometric constraint)
                H = match.homography
                
                # Extract rotation from homography (rough estimate)
                # For pure rotation, H ≈ K R K^-1
                # We just need the angular difference, not absolute rotation
                
                # Use sensor data as baseline
                az_i = photos[i].get('azimuth', 0)
                el_i = photos[i].get('elevation', 0)
                az_j = photos[neighbor_idx].get('azimuth', 0)
                el_j = photos[neighbor_idx].get('elevation', 0)
                
                # Sensor-predicted angular difference
                sensor_delta_az = ((az_j - az_i + 180) % 360) - 180
                sensor_delta_el = el_j - el_i
                
                # Feature-based correction (small adjustment)
                # If homography suggests slightly different alignment, adjust
                # This is a simplified approach; full implementation would
                # decompose H to extract rotation
                
                # Weight by match confidence and inlier count
                weight = match.confidence * match.inliers
                
                # For now, trust sensor data mostly (this prevents drift)
                # Real implementation would extract rotation from H
                delta_az_sum += 0  # Placeholder: would compute from H
                delta_el_sum += 0  # Placeholder: would compute from H
                weight_sum += weight
            
            if weight_sum > 0:
                avg_delta_az = delta_az_sum / weight_sum
                avg_delta_el = delta_el_sum / weight_sum
                
                # CLAMP to max refinement (critical for stability)
                avg_delta_az = np.clip(avg_delta_az, -self.max_refinement_deg, self.max_refinement_deg)
                avg_delta_el = np.clip(avg_delta_el, -self.max_refinement_deg, self.max_refinement_deg)
                
                confidence = min(1.0, weight_sum / 100)
                refinements.append(CameraRefinement(i, avg_delta_az, avg_delta_el, confidence))
            else:
                refinements.append(CameraRefinement(i, 0.0, 0.0, 0.0))
        
        return refinements


