# GAIN COMPENSATION (Brown & Lowe Section 6)
# =============================================================================

class GainCompensator:
    """
    Per-image gain factors for exposure normalization.
    
    From Brown & Lowe 2007, Section 6:
    "The error function is the sum of gain normalised intensity
    errors for all overlapping pixels."
    """
    
    def __init__(self, sigma_n: float = 10.0, sigma_g: float = 0.1):
        self.sigma_n = sigma_n
        self.sigma_g = sigma_g
    
    def compute_gains(
        self,
        images: List[np.ndarray],
        matches: List[ImageMatch]
    ) -> np.ndarray:
        """
        Compute optimal gains using iterative solver.
        
        Minimizes: sum_ij (g_i*I_i - g_j*I_j)^2 + sum_i (1 - g_i)^2
        """
        n = len(images)
        
        if n <= 1 or not matches:
            return np.ones(n)
        
        # Compute mean intensities
        means = np.array([np.mean(img.astype(np.float32)) for img in images])
        
        # Build linear system
        A = np.zeros((n, n))
        b = np.ones(n) / (self.sigma_g ** 2)
        
        for match in matches:
            i, j = match.idx1, match.idx2
            n_overlap = match.inliers * 100  # Rough overlap size
            
            if means[i] > 0 and means[j] > 0:
                ratio = means[i] / means[j]
                coef = n_overlap / (self.sigma_n ** 2)
                
                A[i, i] += coef
                A[j, j] += coef * ratio ** 2
                A[i, j] -= coef * ratio
                A[j, i] -= coef * ratio
        
        # Add regularization
        for i in range(n):
            A[i, i] += 1 / (self.sigma_g ** 2)
        
        # Solve
        try:
            gains = np.linalg.solve(A, b)
            gains = gains / np.mean(gains)  # Normalize
            gains = np.clip(gains, 0.5, 2.0)  # Clamp
        except np.linalg.LinAlgError:
            gains = np.ones(n)
        
        return gains


