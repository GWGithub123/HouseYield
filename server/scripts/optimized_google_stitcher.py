# RANSAC + PROBABILISTIC VERIFICATION (Brown & Lowe Section 3)
# =============================================================================

class RANSACVerifier:
    """
    RANSAC with probabilistic match verification.
    
    From Brown & Lowe 2007, Section 3.2:
    "We compare the probabilities that this set of inliers/outliers
    was generated by a correct image match or by a false image match."
    """
    
    def __init__(
        self,
        ransac_threshold: float = 4.0,
        p_inlier_correct: float = 0.6,  # p1 in paper
        p_inlier_false: float = 0.1,    # p0 in paper
        p_min: float = 0.999
    ):
        self.ransac_threshold = ransac_threshold
        self.p1 = p_inlier_correct
        self.p0 = p_inlier_false
        self.p_min = p_min
    
    def verify_match(
        self,
        pts1: np.ndarray,
        pts2: np.ndarray,
        min_inliers: int = 8
    ) -> Tuple[Optional[np.ndarray], np.ndarray, float]:
        """
        Estimate homography with RANSAC and verify probabilistically.
        
        Returns:
            H: Homography matrix (or None if verification failed)
            mask: Inlier mask
            probability: Probability this is a correct match
        """
        if len(pts1) < 4:
            return None, np.array([]), 0.0
        
        # RANSAC homography estimation
        H, mask = cv2.findHomography(
            pts1.reshape(-1, 1, 2),
            pts2.reshape(-1, 1, 2),
            cv2.RANSAC,
            self.ransac_threshold
        )
        
        if H is None or mask is None:
            return None, np.array([]), 0.0
        
        mask = mask.ravel().astype(bool)
        n_inliers = np.sum(mask)
        n_features = len(mask)
        
        if n_inliers < min_inliers:
            return None, mask, 0.0
        
        # Probabilistic verification (Eq. 10-12 from paper)
        p_correct = self._compute_match_probability(n_inliers, n_features)
        
        if p_correct < self.p_min:
            return None, mask, p_correct
        
        return H, mask, p_correct
    
    def _compute_match_probability(self, n_inliers: int, n_features: int) -> float:
        """
        Compute probability of correct match using Bayesian verification.
        
        From Brown & Lowe Eq. 10-12
        """
        if n_features == 0:
            return 0.0
        
        # Log-likelihood ratio for numerical stability
        log_ratio = n_inliers * np.log(self.p1 / self.p0 + 1e-10)
        log_ratio += (n_features - n_inliers) * np.log((1 - self.p1) / (1 - self.p0) + 1e-10)
        
        # Convert to probability
        prob = 1.0 / (1.0 + np.exp(-log_ratio))
        
        return prob


