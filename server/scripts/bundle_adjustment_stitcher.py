#!/usr/bin/env python3
"""
Bundle Adjustment Panorama Stitcher

Implements the techniques from Brown & Lowe's seminal paper:
"Automatic Panoramic Image Stitching using Invariant Features" (2007)

Key improvements over simple sensor-based stitching:
1. SIFT feature detection with k-NN matching and Lowe's ratio test
2. RANSAC homography estimation with probabilistic verification
3. Bundle adjustment to jointly optimize ALL camera parameters
4. Gain compensation for exposure normalization
5. Multi-band blending using Laplacian pyramids

This should dramatically improve stitching quality to near 1.0.
"""

import cv2
import numpy as np
import math
import sys
from typing import List, Dict, Tuple, Optional
from dataclasses import dataclass
from scipy.optimize import least_squares
from scipy.ndimage import gaussian_filter


# =============================================================================
# DATA STRUCTURES
# =============================================================================

@dataclass
class CameraParams:
    """Camera parameters: 3 rotation angles + focal length"""
    theta1: float  # Rotation around X
    theta2: float  # Rotation around Y  
    theta3: float  # Rotation around Z
    focal: float   # Focal length


@dataclass 
class FeatureMatch:
    """A verified match between two images"""
    img_i: int
    img_j: int
    pts_i: np.ndarray  # Nx2 points in image i
    pts_j: np.ndarray  # Nx2 points in image j
    inlier_mask: np.ndarray
    num_inliers: int


# =============================================================================
# SIFT FEATURE DETECTION AND MATCHING (Section 2 of paper)
# =============================================================================

class SIFTMatcher:
    """
    SIFT feature detection and matching with Lowe's ratio test.
    
    From the paper:
    "SIFT features are invariant under rotation and scale changes,
    our system can handle images with varying orientation and zoom."
    """
    
    def __init__(self, n_features: int = 2000, ratio_threshold: float = 0.75):
        self.n_features = n_features
        self.ratio_threshold = ratio_threshold
        
        # Create SIFT detector
        self.sift = cv2.SIFT_create(
            nfeatures=n_features,
            contrastThreshold=0.04,
            edgeThreshold=10
        )
        
        # FLANN matcher for efficient k-NN search (Section 2 of paper)
        # "k nearest neighbours in feature space (we use k=4)"
        index_params = dict(algorithm=1, trees=5)  # FLANN_INDEX_KDTREE
        search_params = dict(checks=50)
        self.flann = cv2.FlannBasedMatcher(index_params, search_params)
    
    def detect_and_describe(self, image: np.ndarray) -> Tuple[List[cv2.KeyPoint], np.ndarray]:
        """Detect SIFT keypoints and compute descriptors"""
        gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
        keypoints, descriptors = self.sift.detectAndCompute(gray, None)
        return keypoints, descriptors
    
    def match_images(
        self, 
        desc1: np.ndarray, 
        desc2: np.ndarray,
        kp1: List[cv2.KeyPoint],
        kp2: List[cv2.KeyPoint]
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Match features using Lowe's ratio test.
        
        From paper: "Each feature is matched to its k nearest neighbours
        in feature space. A match is accepted if the ratio of distances
        to the first and second nearest neighbours is less than 0.75."
        """
        if desc1 is None or desc2 is None or len(desc1) < 2 or len(desc2) < 2:
            return np.array([]), np.array([])
        
        # k-NN matching
        matches = self.flann.knnMatch(desc1, desc2, k=2)
        
        # Ratio test
        good_pts1 = []
        good_pts2 = []
        
        for match in matches:
            if len(match) == 2:
                m, n = match
                if m.distance < self.ratio_threshold * n.distance:
                    good_pts1.append(kp1[m.queryIdx].pt)
                    good_pts2.append(kp2[m.trainIdx].pt)
        
        return np.array(good_pts1), np.array(good_pts2)


