class BundleAdjustmentStitcher:
    """
    Complete panorama stitcher implementing Brown & Lowe 2007.
    
    Pipeline:
    1. Extract SIFT features from all images
    2. Match features between candidate pairs
    3. Verify matches with RANSAC + probabilistic model
    4. Build image connectivity graph
    5. Bundle adjustment to optimize all cameras jointly
    6. Gain compensation for exposure normalization
    7. Project to equirectangular
    8. Multi-band blending
    """
    
    def __init__(
        self,
        output_width: int = 4096,
        output_height: int = 2048,
        fov_h: float = 75.0,
        fov_v: float = 55.0
    ):
        self.output_width = output_width
        self.output_height = output_height
        self.fov_h = fov_h
        self.fov_v = fov_v
        
        self.matcher = SIFTMatcher()
        self.verifier = RANSACVerifier()
        self.bundle_adjuster = BundleAdjuster()
        self.gain_compensator = GainCompensator()
        self.blender = MultiBandBlender()
    
    def stitch(
        self,
        photos: List[Dict],
        images: List[np.ndarray],
        depth_maps: List[Optional[np.ndarray]] = None
    ) -> Tuple[np.ndarray, Optional[np.ndarray], Dict]:
        """
        Main stitching function.
        
        Returns:
            panorama: Stitched equirectangular image
            depth_panorama: Stitched depth (if available)
            stats: Processing statistics
        """
        n = len(images)
        print(f"[BundleStitch] Processing {n} images...", file=sys.stderr)
        
        # Step 1: Extract features
        print("[BundleStitch] Step 1: Extracting SIFT features...", file=sys.stderr)
        features = []
        for i, img in enumerate(images):
            kp, desc = self.matcher.detect_and_describe(img)
            features.append((kp, desc))
            print(f"  Image {i+1}: {len(kp)} keypoints", file=sys.stderr)
        
        # Step 2: Match candidate pairs
        print("[BundleStitch] Step 2: Matching image pairs...", file=sys.stderr)
        matches = self._find_matches(photos, images, features)
        print(f"  Found {len(matches)} verified pairs", file=sys.stderr)
        
        # Step 3: Initialize camera parameters from sensors
        print("[BundleStitch] Step 3: Initializing cameras...", file=sys.stderr)
        initial_params = self._init_cameras(photos, images)
        
        # Step 4: Bundle adjustment
        print("[BundleStitch] Step 4: Bundle adjustment...", file=sys.stderr)
        image_sizes = [(img.shape[1], img.shape[0]) for img in images]
        
        if matches:
            optimized_params = self.bundle_adjuster.optimize(
                n, matches, initial_params, image_sizes
            )
        else:
            print("  Warning: No verified matches, using sensor positions only", file=sys.stderr)
            optimized_params = initial_params
        
        # Step 5: Gain compensation
        print("[BundleStitch] Step 5: Gain compensation...", file=sys.stderr)
        gains = self.gain_compensator.compute_gains(images, matches)
        images_corrected = self.gain_compensator.apply_gains(images, gains)
        print(f"  Gains: {[f'{g:.2f}' for g in gains]}", file=sys.stderr)
        
        # Step 6: Project and blend
        print("[BundleStitch] Step 6: Projecting and blending...", file=sys.stderr)
        panorama = self._project_and_blend(images_corrected, optimized_params)
        
        # Step 7: Fill gaps
        print("[BundleStitch] Step 7: Filling gaps...", file=sys.stderr)
        panorama = self._fill_gaps(panorama)
        
        # Compute quality metrics
        stats = {
            'photoCount': n,
            'matchedPairs': len(matches),
            'totalInliers': sum(m.num_inliers for m in matches),
            'gains': gains.tolist(),
            'method': 'bundle_adjustment',
            'blending': 'multi_band'
        }
        
        print("[BundleStitch] Complete!", file=sys.stderr)
        return panorama, None, stats
    
    def _find_matches(
        self,
        photos: List[Dict],
        images: List[np.ndarray],
        features: List[Tuple]
    ) -> List[FeatureMatch]:
        """Find and verify all image matches"""
        n = len(images)
        matches = []
        
        # Find candidate pairs by angular proximity
        for i in range(n):
            az_i = photos[i].get('azimuth', 0)
            el_i = photos[i].get('elevation', 0)
            
            for j in range(i + 1, n):
                az_j = photos[j].get('azimuth', 0)
                el_j = photos[j].get('elevation', 0)
                
                # Angular distance
                az_diff = abs(((az_i - az_j + 180) % 360) - 180)
                el_diff = abs(el_i - el_j)
                
                # Skip if too far apart (no expected overlap)
                if az_diff > 50 or el_diff > 50:
                    continue
                
                # Match features
                kp_i, desc_i = features[i]
                kp_j, desc_j = features[j]
                
                pts_i, pts_j = self.matcher.match_images(desc_i, desc_j, kp_i, kp_j)
                
                if len(pts_i) < 10:
                    continue
                
                # Verify with RANSAC
                H, mask, prob = self.verifier.verify_match(pts_i, pts_j)
                
                if H is not None:
                    match = FeatureMatch(
                        img_i=i,
                        img_j=j,
                        pts_i=pts_i,
                        pts_j=pts_j,
                        inlier_mask=mask,
                        num_inliers=int(np.sum(mask))
                    )
                    matches.append(match)
                    print(f"  Pair ({i+1}, {j+1}): {match.num_inliers} inliers, p={prob:.3f}", file=sys.stderr)
        
        return matches
    
    def _init_cameras(
        self,
        photos: List[Dict],
        images: List[np.ndarray]
    ) -> List[CameraParams]:
        """Initialize camera parameters from sensor data"""
        params = []
        
        for i, (photo, img) in enumerate(zip(photos, images)):
            az = math.radians(photo.get('azimuth', 0))
            el = math.radians(photo.get('elevation', 0))
            
            # Convert to rotation vector
            # theta2 = azimuth (rotation around Y)
            # theta1 = elevation (rotation around X)
            theta1 = -el
            theta2 = az
            theta3 = 0.0
            
            # Estimate focal length from FOV
            w = img.shape[1]
            focal = w / (2 * math.tan(math.radians(self.fov_h / 2)))
            
            params.append(CameraParams(
                theta1=theta1,
                theta2=theta2,
                theta3=theta3,
                focal=focal
            ))
        
        return params
    
    def _params_to_rotation(self, params: CameraParams) -> np.ndarray:
        """Convert camera parameters to rotation matrix"""
        theta = np.array([params.theta1, params.theta2, params.theta3])
        
        angle = np.linalg.norm(theta)
        if angle < 1e-8:
            return np.eye(3)
        
        axis = theta / angle
        K = np.array([
            [0, -axis[2], axis[1]],
            [axis[2], 0, -axis[0]],
            [-axis[1], axis[0], 0]
        ])
        
        return np.eye(3) + np.sin(angle) * K + (1 - np.cos(angle)) * (K @ K)
    
    def _project_and_blend(
        self,
        images: List[np.ndarray],
        params: List[CameraParams]
    ) -> np.ndarray:
        """Project images and blend using multi-band"""
        h, w = self.output_height, self.output_width
        
        # Project each image
        projections = []
        
        for i, (img, p) in enumerate(zip(images, params)):
            print(f"  Projecting image {i+1}...", file=sys.stderr)
            
            R = self._params_to_rotation(p)
            projected, weight = self._project_single(img, R, p.focal)
            projections.append((projected, weight))
        
        # Multi-band blend
        print("  Multi-band blending...", file=sys.stderr)
        panorama = self.blender.blend_panorama(projections, (h, w))
        
        return panorama
    
    def _project_single(
        self,
        img: np.ndarray,
        R: np.ndarray,
        focal: float
    ) -> Tuple[np.ndarray, np.ndarray]:
        """Project single image to equirectangular"""
        h_out, w_out = self.output_height, self.output_width
        h_in, w_in = img.shape[:2]
        
        projected = np.zeros((h_out, w_out, 3), dtype=np.float32)
        weight = np.zeros((h_out, w_out), dtype=np.float32)
        
        cx, cy = w_in / 2, h_in / 2
        R_inv = R.T
        
        for v in range(h_out):
            phi = (0.5 - v / h_out) * math.pi
            
            for u in range(w_out):
                theta = (u / w_out - 0.5) * 2 * math.pi
                
                # 3D direction
                world_dir = np.array([
                    math.cos(phi) * math.sin(theta),
                    math.sin(phi),
                    math.cos(phi) * math.cos(theta)
                ])
                
                # Transform to camera frame
                cam_dir = R_inv @ world_dir
                
                if cam_dir[2] <= 0.01:
                    continue
                
                # Project
                img_x = focal * (cam_dir[0] / cam_dir[2]) + cx
                img_y = focal * (cam_dir[1] / cam_dir[2]) + cy
                
                if 0 <= img_x < w_in - 1 and 0 <= img_y < h_in - 1:
                    # Bilinear interpolation
                    x0, y0 = int(img_x), int(img_y)
                    dx, dy = img_x - x0, img_y - y0
                    
                    color = (
                        img[y0, x0] * (1-dx) * (1-dy) +
                        img[y0, min(x0+1, w_in-1)] * dx * (1-dy) +
                        img[min(y0+1, h_in-1), x0] * (1-dx) * dy +
                        img[min(y0+1, h_in-1), min(x0+1, w_in-1)] * dx * dy
                    )
                    
                    projected[v, u] = color
                    
                    # Weight with smooth falloff
                    dist_x = abs(img_x - cx) / (w_in / 2)
                    dist_y = abs(img_y - cy) / (h_in / 2)
                    dist = math.sqrt(dist_x**2 + dist_y**2)
                    weight[v, u] = max(0, 1 - dist**2)
        
        return projected, weight
    
    def _fill_gaps(self, panorama: np.ndarray) -> np.ndarray:
        """Fill gaps using inpainting"""
        gaps = np.all(panorama == 0, axis=2)
        gap_count = np.sum(gaps)
        
        if gap_count > 0:
            print(f"  Filling {gap_count} gap pixels...", file=sys.stderr)
            gap_mask = gaps.astype(np.uint8) * 255
            panorama = cv2.inpaint(panorama, gap_mask, 10, cv2.INPAINT_TELEA)
        
        return panorama


