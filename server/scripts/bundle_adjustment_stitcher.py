class BundleAdjuster:
    """
    Bundle adjustment to jointly optimize all camera parameters.
    
    From paper Section 4:
    "We use bundle adjustment to solve for all of the camera parameters
    jointly. This is an essential step as concatenation of pairwise
    homographies would cause accumulated errors."
    
    Minimizes the robustified sum squared projection error (Eq. 16):
    e = sum_i sum_j sum_k h(r_ij^k)
    
    where r_ij^k is the residual between projected and observed feature location.
    """
    
    def __init__(
        self,
        huber_sigma: float = 2.0,  # sigma in Huber robust function
        max_iterations: int = 100
    ):
        self.sigma = huber_sigma
        self.max_iterations = max_iterations
    
    def optimize(
        self,
        n_images: int,
        matches: List[FeatureMatch],
        initial_params: List[CameraParams],
        image_sizes: List[Tuple[int, int]]
    ) -> List[CameraParams]:
        """
        Run bundle adjustment optimization.
        
        Args:
            n_images: Number of images
            matches: List of verified feature matches
            initial_params: Initial camera parameters from sensor data
            image_sizes: (width, height) for each image
            
        Returns:
            Optimized camera parameters
        """
        if not matches:
            return initial_params
        
        print(f"[BundleAdjust] Optimizing {n_images} cameras with {len(matches)} image pairs", file=sys.stderr)
        
        # Pack parameters into vector: [theta1, theta2, theta3, focal] * n_images
        x0 = self._pack_params(initial_params)
        
        # Run Levenberg-Marquardt optimization
        result = least_squares(
            self._compute_residuals,
            x0,
            args=(matches, image_sizes),
            method='lm',
            max_nfev=self.max_iterations * len(x0),
            verbose=0
        )
        
        if result.success:
            print(f"[BundleAdjust] Converged after {result.nfev} evaluations", file=sys.stderr)
        else:
            print(f"[BundleAdjust] Warning: {result.message}", file=sys.stderr)
        
        return self._unpack_params(result.x, n_images)
    
    def _pack_params(self, params: List[CameraParams]) -> np.ndarray:
        """Pack camera parameters into flat vector"""
        x = []
        for p in params:
            x.extend([p.theta1, p.theta2, p.theta3, p.focal])
        return np.array(x)
    
    def _unpack_params(self, x: np.ndarray, n: int) -> List[CameraParams]:
        """Unpack flat vector into camera parameters"""
        params = []
        for i in range(n):
            idx = i * 4
            params.append(CameraParams(
                theta1=x[idx],
                theta2=x[idx + 1],
                theta3=x[idx + 2],
                focal=x[idx + 3]
            ))
        return params
    
    def _compute_residuals(
        self,
        x: np.ndarray,
        matches: List[FeatureMatch],
        image_sizes: List[Tuple[int, int]]
    ) -> np.ndarray:
        """
        Compute all residuals for bundle adjustment.
        
        For each feature match (u_i, u_j), compute:
        r = u_i - proj(R_i @ R_j^T @ unproj(u_j))
        
        Apply Huber robust function to downweight outliers.
        
        CRITICAL FIX: Pre-compute expected residual count to ensure
        consistent array size across iterations (fixes scipy error).
        """
        n = len(image_sizes)
        params = self._unpack_params(x, n)
        
        # Pre-allocate fixed-size array based on total possible residuals
        # Each inlier can produce 2 residuals (dx, dy)
        total_inliers = sum(match.num_inliers for match in matches)
        residuals = np.zeros(total_inliers * 2)
        residual_idx = 0
        
        for match in matches:
            i, j = match.img_i, match.img_j
            w_i, h_i = image_sizes[i]
            w_j, h_j = image_sizes[j]
            
            # Get rotation matrices
            R_i = self._params_to_rotation(params[i])
            R_j = self._params_to_rotation(params[j])
            f_i = params[i].focal
            f_j = params[j].focal
            
            # Relative rotation
            R_rel = R_i @ R_j.T
            
            # For each inlier point pair
            for k in range(len(match.pts_i)):
                if not match.inlier_mask[k]:
                    continue
                
                pt_i = match.pts_i[k]
                pt_j = match.pts_j[k]
                
                # Unproject point j to 3D ray
                ray_j = np.array([
                    (pt_j[0] - w_j / 2) / f_j,
                    (pt_j[1] - h_j / 2) / f_j,
                    1.0
                ])
                ray_j = ray_j / np.linalg.norm(ray_j)
                
                # Transform to image i frame
                ray_i = R_rel @ ray_j
                
                # Always compute residual (even if behind camera)
                # This ensures consistent array size
                if ray_i[2] > 0.01:
                    proj_x = f_i * ray_i[0] / ray_i[2] + w_i / 2
                    proj_y = f_i * ray_i[1] / ray_i[2] + h_i / 2
                    
                    # Residual
                    dx = pt_i[0] - proj_x
                    dy = pt_i[1] - proj_y
                    
                    # Apply Huber robust function (Eq. 17 from paper)
                    r = np.sqrt(dx**2 + dy**2)
                    if r < self.sigma:
                        residuals[residual_idx] = dx
                        residuals[residual_idx + 1] = dy
                    else:
                        # Robust: sqrt(2*sigma*|r| - sigma^2)
                        scale = np.sqrt(2 * self.sigma / (r + 1e-6))
                        residuals[residual_idx] = dx * scale
                        residuals[residual_idx + 1] = dy * scale
                else:
                    # Behind camera: assign large residual to downweight
                    residuals[residual_idx] = 100.0
                    residuals[residual_idx + 1] = 100.0
                
                residual_idx += 2
        
        return residuals
    
    def _params_to_rotation(self, params: CameraParams) -> np.ndarray:
        """Convert camera parameters to rotation matrix using exponential map (Eq. 3)"""
        theta = np.array([params.theta1, params.theta2, params.theta3])
        
        # Rodrigues formula
        angle = np.linalg.norm(theta)
        if angle < 1e-8:
            return np.eye(3)
        
        axis = theta / angle
        K = np.array([
            [0, -axis[2], axis[1]],
            [axis[2], 0, -axis[0]],
            [-axis[1], axis[0], 0]
        ])
        
        R = np.eye(3) + np.sin(angle) * K + (1 - np.cos(angle)) * (K @ K)
        return R


