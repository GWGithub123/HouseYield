# GAIN COMPENSATION (Section 6 of paper)
# =============================================================================

class GainCompensator:
    """
    Compute per-image gain factors for exposure normalization.
    
    From paper Section 6:
    "The error function is the sum of gain normalised intensity
    errors for all overlapping pixels."
    
    Minimizes: e = sum_ij sum_u (g_i*I_i(u) - g_j*I_j(u))^2 / sigma_N^2
                   + sum_i (1 - g_i)^2 / sigma_g^2
    """
    
    def __init__(self, sigma_n: float = 10.0, sigma_g: float = 0.1):
        self.sigma_n = sigma_n
        self.sigma_g = sigma_g
    
    def compute_gains(
        self,
        images: List[np.ndarray],
        matches: List[FeatureMatch]
    ) -> np.ndarray:
        """
        Compute optimal gains using closed-form solution (Eq. 29 from paper).
        
        The quadratic objective can be solved by setting derivative to 0.
        """
        n = len(images)
        
        if n <= 1 or not matches:
            return np.ones(n)
        
        # Build linear system: Ag = b
        # A_ii = sum_j N_ij / sigma_N^2 + 1 / sigma_g^2
        # A_ij = -N_ij * mean(I_i) * mean(I_j) / (mean(I_i)^2 * sigma_N^2)  
        # b_i = 1 / sigma_g^2
        
        A = np.zeros((n, n))
        b = np.ones(n) / (self.sigma_g ** 2)
        
        # Compute mean intensities
        means = []
        for img in images:
            means.append(np.mean(img.astype(np.float32)))
        
        # Add constraints from each match
        for match in matches:
            i, j = match.img_i, match.img_j
            n_overlap = match.num_inliers * 100  # Approximate overlap size
            
            if means[i] > 0 and means[j] > 0:
                # Intensity ratio
                ratio = means[i] / means[j]
                
                # Add to matrix
                coef = n_overlap / (self.sigma_n ** 2)
                A[i, i] += coef
                A[j, j] += coef * ratio ** 2
                A[i, j] -= coef * ratio
                A[j, i] -= coef * ratio
        
        # Add regularization term (keep gains near 1)
        for i in range(n):
            A[i, i] += 1 / (self.sigma_g ** 2)
        
        # Solve
        try:
            gains = np.linalg.solve(A, b)
            # Normalize so mean = 1
            gains = gains / np.mean(gains)
            # Clamp to reasonable range
            gains = np.clip(gains, 0.5, 2.0)
        except np.linalg.LinAlgError:
            gains = np.ones(n)
        
        return gains
    
    def apply_gains(
        self,
        images: List[np.ndarray],
        gains: np.ndarray
    ) -> List[np.ndarray]:
        """Apply computed gains to images"""
        result = []
        for img, g in zip(images, gains):
            adjusted = np.clip(img.astype(np.float32) * g, 0, 255).astype(np.uint8)
            result.append(adjusted)
        return result


