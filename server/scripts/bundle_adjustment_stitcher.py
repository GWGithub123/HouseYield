class MultiBandBlender:
    """
    Multi-band blending using Laplacian pyramids.
    
    From paper Section 7:
    "The idea behind multi-band blending is to blend low frequencies
    over a large spatial range, and high frequencies over a short range."
    
    This preserves fine details while smoothly blending exposure differences.
    """
    
    def __init__(self, n_bands: int = 5, sigma: float = 5.0):
        self.n_bands = n_bands
        self.sigma = sigma
    
    def blend_panorama(
        self,
        projections: List[Tuple[np.ndarray, np.ndarray]],
        output_size: Tuple[int, int]
    ) -> np.ndarray:
        """
        Blend multiple projected images using multi-band blending.
        
        Args:
            projections: List of (color_image, weight_mask) tuples
            output_size: (height, width) of output
            
        Returns:
            Blended panorama
        """
        h, w = output_size
        
        # Build weight maps for each image (Eq. 31 from paper)
        # W_max = 1 where this image has highest weight, 0 elsewhere
        combined_weights = np.zeros((h, w), dtype=np.float32)
        for _, weight in projections:
            combined_weights = np.maximum(combined_weights, weight)
        
        max_weight_maps = []
        for _, weight in projections:
            max_map = (weight >= combined_weights - 1e-6).astype(np.float32)
            max_weight_maps.append(max_map)
        
        # Build Laplacian pyramids for each image
        laplacian_pyramids = []
        weight_pyramids = []
        
        for (color, _), w_max in zip(projections, max_weight_maps):
            lap_pyr = self._build_laplacian_pyramid(color.astype(np.float32))
            w_pyr = self._build_gaussian_pyramid(w_max)
            laplacian_pyramids.append(lap_pyr)
            weight_pyramids.append(w_pyr)
        
        # Blend each band (Eq. 38 from paper)
        blended_pyramid = []
        
        for level in range(self.n_bands):
            blended_level = np.zeros_like(laplacian_pyramids[0][level])
            weight_sum = np.zeros(laplacian_pyramids[0][level].shape[:2], dtype=np.float32)
            
            for lap_pyr, w_pyr in zip(laplacian_pyramids, weight_pyramids):
                # Expand weight to match Laplacian shape if needed
                w = w_pyr[level]
                if len(blended_level.shape) == 3:
                    w = w[:, :, np.newaxis]
                
                blended_level += lap_pyr[level] * w
                weight_sum += w_pyr[level]
            
            # Normalize by total weight
            weight_sum = np.maximum(weight_sum, 1e-6)
            if len(blended_level.shape) == 3:
                weight_sum = weight_sum[:, :, np.newaxis]
            blended_level /= weight_sum
            
            blended_pyramid.append(blended_level)
        
        # Collapse pyramid
        result = self._collapse_laplacian_pyramid(blended_pyramid)
        
        return np.clip(result, 0, 255).astype(np.uint8)
    
    def _build_gaussian_pyramid(self, image: np.ndarray) -> List[np.ndarray]:
        """Build Gaussian pyramid"""
        pyramid = [image.astype(np.float32)]
        
        for _ in range(self.n_bands - 1):
            # Blur and downsample
            blurred = gaussian_filter(pyramid[-1], self.sigma)
            downsampled = blurred[::2, ::2] if len(blurred.shape) == 2 else blurred[::2, ::2, :]
            pyramid.append(downsampled)
        
        return pyramid
    
    def _build_laplacian_pyramid(self, image: np.ndarray) -> List[np.ndarray]:
        """Build Laplacian pyramid (Eq. 32-33 from paper)"""
        gaussian = self._build_gaussian_pyramid(image)
        laplacian = []
        
        for i in range(len(gaussian) - 1):
            # Upsample next level
            if len(gaussian[i].shape) == 2:
                h, w = gaussian[i].shape
            else:
                h, w = gaussian[i].shape[:2]
            
            upsampled = cv2.resize(gaussian[i + 1], (w, h), interpolation=cv2.INTER_LINEAR)
            
            # Difference = high frequencies at this level
            laplacian.append(gaussian[i] - upsampled)
        
        # Coarsest level is low-frequency residual
        laplacian.append(gaussian[-1])
        
        return laplacian
    
    def _collapse_laplacian_pyramid(self, pyramid: List[np.ndarray]) -> np.ndarray:
        """Reconstruct image from Laplacian pyramid"""
        result = pyramid[-1]
        
        for i in range(len(pyramid) - 2, -1, -1):
            # Upsample
            if len(pyramid[i].shape) == 2:
                h, w = pyramid[i].shape
            else:
                h, w = pyramid[i].shape[:2]
            
            result = cv2.resize(result, (w, h), interpolation=cv2.INTER_LINEAR)
            result = result + pyramid[i]
        
        return result


